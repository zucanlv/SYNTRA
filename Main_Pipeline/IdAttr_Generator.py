def generate_idattr_for_doc(
    doc: Dict[str, Any],
    llm_cfg: dict,
    task_name: str = "",
    refinement_guidance: str = "",
    logger: Optional[logging.Logger] = None,
) -> Dict[str, Any]:
    """Generate identifiers and attributes for a single document.

    Parameters
    ----------
    doc : dict
        Must contain ``doc_id`` and ``doc``.
    llm_cfg : dict
        LLM configuration passed to ``qwen_agent.agents.Assistant``.
    task_name : str
        Key into ``HighLevel_Task_Definition`` for task-aware prompting.
    refinement_guidance : str
        Supplementary guidance from the self-refine calibration loop.
    logger : Logger, optional

    Returns
    -------
    dict
        ``{doc_id, doc, identifiers, attributes}``
    """
    log = logger or logging.getLogger(__name__)

    doc_id = doc.get("doc_id") or ""
    doc_content = doc.get("doc") or ""

    prompt = build_idattr_prompt(
        doc=doc_content, task_name=task_name,
        refinement_guidance=refinement_guidance,
    )

    designer = Assistant(llm=llm_cfg)
    raw_output = ""
    for response in designer.run([{"role": "user", "content": prompt}]):
        raw_output = response[-1]["content"]

    try:
        parsed = json5.loads(raw_output)
    except Exception as e:
        log.warning("Failed to parse LLM JSON for doc_id=%s: %s", doc_id, e)
        parsed = {}

    return {
        "doc_id": doc_id,
        "doc": doc_content,
        "identifiers": parsed.get("identifiers", []),
        "attributes": parsed.get("attributes", []),
    }


