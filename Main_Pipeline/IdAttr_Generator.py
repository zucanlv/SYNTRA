def build_idattr_prompt(
    doc: str,
    task_name: str = "",
    refinement_guidance: str = "",
) -> str:
    """Build the LLM prompt for identifier/attribute generation.

    When *task_name* matches a key in ``HighLevel_Task_Definition``, the
    prompt includes task-specific context so the LLM can tailor identifiers
    and attribute dimensions to the downstream IR task.

    Parameters
    ----------
    refinement_guidance : str
        Optional supplementary guidance produced by the self-refine prompt
        calibration loop.  Inserted between Task Context and Core Definitions
        to steer the LLM without altering the structural constraints.
    """
    task_context = ""
    if task_name and task_name in HighLevel_Task_Definition:
        query_type, doc_type, relevance_def = HighLevel_Task_Definition[task_name]
        task_context = f"""
## Task Context (use this to guide your analysis)
- This document is a: {doc_type}
- Queries that will target this document are: {query_type}
- Relevance criteria: {relevance_def}
- Tailor both identifiers and attribute dimensions so they are maximally
  useful for generating diverse queries of the above type.
"""

    refinement_section = ""
    if refinement_guidance and refinement_guidance.strip():
        refinement_section = f"""
## Refined Guidance (from prompt calibration — follow strictly)
{refinement_guidance.strip()}
"""

    return f"""You are a professional data synthesis and NLP expert. Your task is to analyze the document and produce two outputs for downstream diverse and high-quality query generation:
1) Document Identifiers (information anchors)
2) Query Attributes (style/format/constraint dimensions with options)

{task_context}


## Core Definitions (must follow strictly)
- Identifier (Information Anchor): An irreplaceable core entity/relationship extracted directly from the document. It serves as the anchor that diverse queries should target. Do NOT include redundant/irrelevant details. Do NOT use external knowledge.
  - Entity-type: concrete objects in the document (e.g., people, places, events, records/results).
  - Relationship-type: unique relationships/logic between entities stated or implied by the document (e.g., relations between people, places, events, records/results).
- Query Attribute: a non-core feature dimension controlling how queries are asked. Attributes should NOT introduce new core facts; they should steer query diversity while keeping identifiers as the information anchors.
  - Example dimensions (for inspiration only; you may adopt, adapt, or omit): reasoning depth, answer form, topic specificity. These are common dimensions, but not all documents or query types need every one.
  - Brainstorm step: Besides considering the above examples, brainstorm 5-7 more independent dimensions by carefully analyzing THIS document (domain, topic, structure, content type, and what kinds of queries would realistically target it). Each dimension must be independent (no overlap with others), practical for query generation, and have 2-4 mutually exclusive options in mind.
  - Selection step (reason step-by-step): First, analyze the Task Context and the Input Document. Then strictly filter the full pool (example-inspired + brainstormed, typically 8-10 candidate dimensions) **using the Scientific Approach below**, and select exactly 3-6 dimensions that are most useful for diversifying queries over THIS document. Output only these 3-6 selected dimensions in the final JSON.

## 🔬 Critical: Scientific Approach to Attribute Design
Before finalizing your Identifiers and Attributes, you MUST perform a "Task Alignment Analysis". Answer these questions:
1. **WHAT makes this task unique?**
   - Identify specific patterns, challenges, or domain characteristics of {query_type}. (Do not just repeat the task context; explain what it means in practice).
2. **WHY is each selected attribute suitable?**
   - Explain the MATCH between the attribute and the task characteristics. How does it help generate high-quality queries?
3. **MULTIPLE OPTIONS TEST (Crucial):**
   - Does the attribute genuinely have multiple valid, mutually exclusive options for THIS specific task?
   - ⚠️ CRITICAL RULE: If the task context restricts an attribute to only ONE valid option, you MUST NOT select it! (e.g., If it's a reasoning-intensive task, "reasoning depth" should always be "high", so "reasoning depth" is NOT a valid diversifying attribute).
⚠️ This is not a template to fill - this is how experts think.
Blindly applying standard methods without understanding WHY is not acceptable.

## High-Quality Query Attributes Criteria
1. Strictly align with the characteristics of {query_type}.
2. Each selected dimension must have 2-4 mutually exclusive, actionable options applicable to THIS document.

{refinement_section}

## Input Document
doc: {doc}

## Output Format Requirements (MANDATORY, machine-parsable, no deviation)
- Output MUST be a single valid JSON object (RFC 8259).
- Output MUST contain ONLY the JSON object: no Markdown, no code fences, no commentary, no extra keys, no trailing text.
- Use double quotes for all strings and keys. No trailing commas.
- The JSON must start with a single left brace and end with a single right brace.
- Note: In this prompt template you may see doubled braces (e.g., `{{{{` / `}}}}`) due to Python string escaping; your OUTPUT JSON must use normal single braces.

## Hard constraints
- identifiers: 3-10 items; no duplicates/overlap; each must be a standalone anchor.
- attributes: 3-6 dimensions total. Produce them by (1) using the example dimensions only as inspiration, (2) brainstorming from THIS document, then (3) filtering via the Scientific Approach. Each dimension unique; each must have 2-4 options.
- options must be mutually exclusive, actionable, and applicable to THIS document's domain/topic for practical query generation.

## JSON schema (fixed keys; output MUST follow exactly)
{{
  "identifiers": [
    {{
      "type": "entity" | "relationship",
      "identifier": "string (copied/derived from document only; no external info)",
      "label": "string (3-8 words; short unique label)"
    }}
  ],
  "attributes": [
    {{
      "dimension": "string (clear independent dimension name)",
      "options": ["string", "string", "string", "string (optional)"]
    }}
  ]
}}"""


