def generate_idattr(
    config: Optional[Union[IdAttrConfig, dict]] = None,
    logger: Optional[logging.Logger] = None,
) -> str:
    """Generate identifiers and attributes for all documents in the input file.

    Returns the path to the output JSONL file.

    When ``logger`` is provided (e.g. when called from main pipeline), that logger
    is used and the root logging config is left unchanged. When ``logger`` is None
    (e.g. when run as standalone script), logging is configured here and output
    goes to IdAttr_Generator_*.log.
    """
    if config is None:
        config = IdAttrConfig()
    elif isinstance(config, dict):
        config = IdAttrConfig.from_dict(config)

    if logger is None:
        logger = _setup_logging(config)

    try:
        os.makedirs(config.output_dir, exist_ok=True)

        # ---- Validate inputs -------------------------------------------------
        if not config.input_path or not os.path.isfile(config.input_path):
            raise FileNotFoundError(f"Input file not found: {config.input_path}")

        if config.task_name and config.task_name not in HighLevel_Task_Definition:
            logger.warning(
                "task_name '%s' not in HighLevel_Task_Definition; "
                "proceeding without task context.", config.task_name,
            )

        llm_cfg = config.get_llm_cfg()
        logger.info("LLM config: model=%s", llm_cfg["model"])

        # ---- Load input documents --------------------------------------------
        logger.info("Loading documents from %s ...", config.input_path)
        docs: List[Dict[str, Any]] = []
        with open(config.input_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    obj = json.loads(line)
                    docs.append(obj)
                except Exception as e:
                    logger.warning("Skipping malformed line: %s", e)

        total = len(docs)
        logger.info("Loaded %d documents.", total)

        # ---- Sampling --------------------------------------------------------
        if config.limit is not None and config.limit < total:
            if config.seed is not None:
                random.seed(config.seed)
            docs = random.sample(docs, config.limit)
            logger.info("Sampled %d documents (seed=%s).", len(docs), config.seed)

        # ---- Resume ----------------------------------------------------------
        processed_ids: Set[str] = set()
        output_file: str
        open_mode: str

        if config.resume_path and os.path.isfile(config.resume_path):
            processed_ids = _load_processed_ids(config.resume_path, logger)
            output_file = config.resume_path
            open_mode = "a"
        else:
            ts = datetime.now().strftime("%Y%m%d_%H%M%S")
            output_file = os.path.join(config.output_dir, f"IdAttr_{ts}.jsonl")
            open_mode = "w"

        docs_to_process = [d for d in docs if d.get("doc_id") not in processed_ids]
        num_skipped = len(docs) - len(docs_to_process)
        if num_skipped > 0:
            logger.info("Skipping %d already-processed documents.", num_skipped)
        num_to_process = len(docs_to_process)
        logger.info("Documents to process: %d", num_to_process)

        if num_to_process == 0:
            logger.info("Nothing to process. Output: %s", output_file)
            return output_file

        # ---- Process documents -----------------------------------------------
        logger.info(
            "Processing %d documents (concurrency=%s, max_workers=%s, jitter=%.2f) ...",
            num_to_process, config.concurrency_enabled, config.max_workers, config.jitter,
        )

        def _process_one(doc: Dict[str, Any]) -> Optional[Dict[str, Any]]:
            doc_id = doc.get("doc_id", "unknown")
            try:
                return generate_idattr_for_doc(
                    doc=doc,
                    llm_cfg=llm_cfg,
                    task_name=config.task_name,
                    refinement_guidance=config.refinement_guidance or "",
                    logger=logger,
                )
            except Exception as e:
                logger.error("Error processing doc_id=%s: %s", doc_id, e)
                return None

        results = run_concurrent(
            _process_one,
            [{"doc": doc} for doc in docs_to_process],
            enabled=config.concurrency_enabled,
            max_workers=config.max_workers,
            jitter=config.jitter,
            progress_logger=logger,
            progress_label="Step 3.1 IdAttr generation",
            progress_interval_sec=config.progress_log_interval_sec,
        )

        success_count = 0
        with open(output_file, open_mode, encoding="utf-8") as out_f:
            for result in results:
                if result is not None:
                    normalized_result = _normalize_surrogates(result)
                    out_f.write(json.dumps(normalized_result, ensure_ascii=False) + "\n")
                    success_count += 1

        logger.info(
            "Done. %d/%d documents processed successfully.", success_count, num_to_process,
        )
        logger.info("Output: %s", output_file)
        return output_file

    except Exception:
        logger.error("Error in generate_idattr", exc_info=True)
        raise


