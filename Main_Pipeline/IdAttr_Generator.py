def parse_args(args=None) -> IdAttrConfig:
    p = argparse.ArgumentParser(
        description="Generate identifiers and attributes for diverse documents."
    )
    p.add_argument("--config", type=str, default=None, help="JSON config file.")

    # Input
    p.add_argument(
        "--input", type=str, default=None, dest="input_path",
        help="Input JSONL from Text_Diverse_Selection (fields: doc_id, title, text).",
    )
    p.add_argument(
        "--task", type=str, default=None, dest="task_name",
        help="Task name from HighLevel_Task_Definition (e.g. arguana, msmarco).",
    )

    # Output
    p.add_argument("--output-dir", type=str, default=None)
    p.add_argument("--log-dir", type=str, default=None)

    # LLM
    p.add_argument("--model", type=str, default=None)
    p.add_argument("--model-server", type=str, default=None, dest="model_server")
    p.add_argument("--api-key", type=str, default=None, dest="api_key")

    # Processing
    p.add_argument("--limit", type=int, default=None,
                   help="Max documents to process (default: all).")
    p.add_argument("--seed", type=int, default=None,
                   help="Random seed for sampling when using --limit.")

    # Resume
    p.add_argument("--resume", type=str, default=None, dest="resume_path",
                   help="Existing output JSONL to resume from (skip processed doc_ids).")

    parsed = p.parse_args(args)

    if parsed.config and os.path.isfile(parsed.config):
        with open(parsed.config, "r", encoding="utf-8") as f:
            config = IdAttrConfig.from_dict(json.load(f))
    else:
        config = IdAttrConfig()

    for field in IdAttrConfig.__dataclass_fields__:
        val = getattr(parsed, field, None)
        if val is not None:
            setattr(config, field, val)

    return config


