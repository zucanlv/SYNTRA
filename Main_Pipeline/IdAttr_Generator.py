@register_tool("idattr_generator")
class IdAttrGenerator(BaseTool):
    """File-in / file-out wrapper around ``generate_idattr()``.

    Reads a JSONL of documents produced by ``Text_Diverse_Selection``,
    generates identifiers and attributes for each document, and writes
    results to a new JSONL under ``output_dir``.  Returns the output
    file path so downstream pipeline steps can chain directly.
    """

    description = (
        "Generate semantic identifiers and query attribute dimensions for "
        "every document in an input JSONL file. Writes results to a new "
        "JSONL and returns its path."
    )
    parameters = [
        # ---- Input -----------------------------------------------------------
        {
            "name": "input_path",
            "type": "string",
            "description": (
                "Path to the input JSONL file (output of Text_Diverse_Selection). "
                "Each line must have fields: doc_id, text, and optionally title."
            ),
            "required": True,
        },
        {
            "name": "task_name",
            "type": "string",
            "description": (
                'Task key from HighLevel_Task_Definition (e.g. "msmarco"). '
                "Enables task-aware prompting. Case-insensitive."
            ),
            "required": False,
        },
        # ---- Output ----------------------------------------------------------
        {
            "name": "output_dir",
            "type": "string",
            "description": 'Directory for the output JSONL. Defaults to "Results".',
            "required": False,
        },
        {
            "name": "log_dir",
            "type": "string",
            "description": 'Directory for log files. Defaults to "Logs".',
            "required": False,
        },
        # ---- Processing ------------------------------------------------------
        {
            "name": "limit",
            "type": "number",
            "description": "Max number of documents to process. Omit to process all.",
            "required": False,
        },
        {
            "name": "seed",
            "type": "number",
            "description": "Random seed used when sampling with --limit.",
            "required": False,
        },
        # ---- Resume ----------------------------------------------------------
        {
            "name": "resume_path",
            "type": "string",
            "description": (
                "Path to an existing output JSONL to resume from. "
                "Already-processed doc_ids are skipped; new results are appended."
            ),
            "required": False,
        },
    ]

    def call(self, params: str, **kwargs) -> str:
        params_dict = json5.loads(params)

        _kwarg_cfg: dict = kwargs.get("llm_cfg", {})

        config = IdAttrConfig(
            input_path=params_dict.get("input_path", ""),
            task_name=(params_dict.get("task_name") or "").lower(),
            output_dir=params_dict.get("output_dir") or "Results",
            log_dir=params_dict.get("log_dir") or "Logs",
            model=(
                _kwarg_cfg.get("model")
                or "gpt-4o-mini"
            ),
            model_server=(
                _kwarg_cfg.get("model_server")
                or os.getenv("OPENAI_BASE_URL")
            ),
            api_key=(
                _kwarg_cfg.get("api_key")
                or os.getenv("OPENAI_API_KEY")
            ),
            limit=params_dict.get("limit"),
            seed=params_dict.get("seed"),
            resume_path=params_dict.get("resume_path"),
        )

        output_file = generate_idattr(config)
        return json5.dumps({"output_path": output_file}, ensure_ascii=False)


