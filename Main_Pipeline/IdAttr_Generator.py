def _load_processed_ids(path: str, logger) -> Set[str]:
    """Read an existing output JSONL and return the set of already-processed doc_ids."""
    processed: Set[str] = set()
    if not path or not os.path.isfile(path):
        return processed
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
                did = obj.get("doc_id")
                if did:
                    processed.add(did)
            except Exception:
                pass
    logger.info("Resume: loaded %d already-processed doc_ids from %s", len(processed), path)
    return processed


def _normalize_surrogates(value: Any) -> Any:
    """Recursively replace UTF-16 surrogate code points with valid Unicode."""
    if isinstance(value, str):
        if not any(0xD800 <= ord(char) <= 0xDFFF for char in value):
            return value
        return value.encode("utf-16", "surrogatepass").decode("utf-16", "replace")
    if isinstance(value, list):
        return [_normalize_surrogates(item) for item in value]
    if isinstance(value, dict):
        return {
            _normalize_surrogates(key): _normalize_surrogates(item)
            for key, item in value.items()
        }
    return value


