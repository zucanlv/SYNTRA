@dataclass
class IdAttrConfig:
    """All paths and hyper-parameters for identifier/attribute generation."""

    # Input
    input_path: str = ""
    task_name: str = ""

    # Output
    output_dir: str = "Results"
    log_dir: str = "Logs"

    # LLM
    model: str = "gpt-4o-mini"
    model_server: Optional[str] = None
    api_key: Optional[str] = None

    # Processing (when limit < total docs, randomly sample that many; pipeline test-mode
    # can pass limit/seed from main.py to run Step 3 on a small subset of diverse texts)
    limit: Optional[int] = None
    seed: Optional[int] = None

    # Resume
    resume_path: Optional[str] = None

    # Self-refine: supplementary guidance generated by the prompt calibration loop
    refinement_guidance: Optional[str] = None

    # Concurrency
    concurrency_enabled: bool = False
    max_workers: Optional[int] = None
    jitter: float = 0.0

    # Progress lines on *logger* (e.g. main pipeline log): same semantics as main ``progress_log_interval_sec``.
    progress_log_interval_sec: float = 0.0

    # -- helpers --

    def get_llm_cfg(self) -> dict:
        model_server = self.model_server or os.getenv("OPENAI_BASE_URL")
        api_key = self.api_key or os.getenv("OPENAI_API_KEY")
        return {
            "model": self.model,
            "model_server": model_server if model_server is not None else "",
            "api_key": api_key,
        }

    @classmethod
    def from_dict(cls, d: dict) -> "IdAttrConfig":
        return cls(**{k: v for k, v in d.items() if k in cls.__dataclass_fields__})

    def to_dict(self) -> dict:
        return {k: getattr(self, k) for k in self.__dataclass_fields__}


