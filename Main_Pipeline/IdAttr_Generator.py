def evaluate_idattr_outputs(
    results: List[Dict[str, Any]],
    task_name: str,
    llm_cfg: dict,
    logger: Optional[logging.Logger] = None,
) -> tuple:
    """Evaluate a batch of IdAttr outputs using the LLM.

    Returns
    -------
    (passed: bool, feedback: str)
    """
    log = logger or logging.getLogger(__name__)
    prompt = build_idattr_evaluate_prompt(results, task_name)

    evaluator = Assistant(llm=llm_cfg)
    raw = ""
    for response in evaluator.run([{"role": "user", "content": prompt}]):
        raw = response[-1]["content"]

    eval_details: dict = {}
    try:
        parsed = json5.loads(raw)
        score = parsed.get("overall_score", 0)
        passed = score >= 2
        parts = []
        if parsed.get("feedback"):
            parts.append(parsed["feedback"])
        if parsed.get("identifier_issues") and parsed["identifier_issues"].lower() != "none":
            parts.append(f"Identifier issues: {parsed['identifier_issues']}")
        if parsed.get("attribute_issues") and parsed["attribute_issues"].lower() != "none":
            parts.append(f"Attribute issues: {parsed['attribute_issues']}")
        if parsed.get("suggestions"):
            parts.append(f"Suggestions: {parsed['suggestions']}")
        feedback = "\n".join(parts)
        eval_details = {
            "score": score,
            "feedback": parsed.get("feedback", ""),
            "identifier_issues": parsed.get("identifier_issues", ""),
            "attribute_issues": parsed.get("attribute_issues", ""),
            "suggestions": parsed.get("suggestions", ""),
        }
        log.info("IdAttr evaluation: passed=%s score=%s", passed, score)
    except Exception as e:
        log.warning("Failed to parse evaluation JSON: %s — treating as not passed", e)
        passed = False
        feedback = f"Evaluation parse error. Raw output:\n{raw[:1000]}"

    return passed, feedback, eval_details


def build_idattr_refine_prompt(
    current_guidance: str,
    results: List[Dict[str, Any]],
    feedback: str,
    task_name: str,
) -> str:
    """Build a prompt that asks the LLM to produce refined guidance.

    The refiner reads the evaluation feedback and the current sample outputs,
    then writes a focused guidance addendum to be inserted into the IdAttr
    generation prompt.
    """
    query_type, doc_type, relevance_def = HighLevel_Task_Definition[task_name]

    samples_brief = json.dumps(
        [
            {
                "doc_id": r.get("doc_id", ""),
                "identifiers": r.get("identifiers", []),
                "attributes": r.get("attributes", []),
            }
            for r in results
        ],
        ensure_ascii=False,
        indent=2,
    )

    prev_guidance_section = f"""
## Previous Guidance (the last addendum that was tried)
There was no previous guidance that was tried before.
"""
    if current_guidance and current_guidance.strip():
        prev_guidance_section = f"""
## Previous Guidance (the last addendum that was tried)
{current_guidance.strip()}
"""

    return f"""You are a prompt engineering expert specializing in information retrieval data synthesis.

## Context
We have a prompt that instructs an LLM to generate **Identifiers** (information anchors) and **Attributes** (query diversity dimensions) for documents. The generated IdAttr will be used downstream to produce diverse **{query_type}** queries over **{doc_type}** documents.

- Relevance Definition: {relevance_def}

## Problem
The current prompt was evaluated on sample documents and received the following feedback. Note: if this feedback contains **specific examples** (e.g., "Identifier X for doc Y is wrong because ..."), you must **abstract** from these examples into **task-level** lessons.

### Evaluation Feedback
{feedback}

### Sample Outputs (from the current prompt)
{samples_brief}

{prev_guidance_section}

## Your Task (two mental steps — output only the final guidance)

**Step 1 — Summarize and abstract (do this mentally, do not output it):**
- Read the feedback and identify **what went wrong** in the examples.
- **Generalize**: For each type of issue, extract the **underlying principle or pattern** that would help the generator avoid that class of error on **any** document, not just the ones in the sample. Ask: "What rule or criterion would prevent this kind of mistake in general?"

**Step 2 — Write Refined Guidance:**
Produce a **Refined Guidance** addendum that encodes those **task-level, query-agnostic** principles. This guidance will be inserted into the generation prompt and must apply to **all** future IdAttr generation, not to specific docs or queries.

## Requirements for the Refined Guidance
1. **Query-agnostic and task-level only**: Do NOT include doc-specific or query-specific fixes (e.g., do not reference particular doc_id, query text, or "for the query about X do Y"). Write only **general rules** that improve IdAttr generation for the whole task.
2. **Derived from feedback**: Every recurring issue type in the feedback should be reflected as a **general principle** in the guidance.
3. **Preserve what works**: If parts of the previous guidance are effective, keep them.
4. **Specific and actionable**: Say exactly WHAT to prefer/avoid and WHY for this task type.
5. **Concise**: 100-300 words. Dense, high-signal, imperative tone (e.g., "Prioritize ...", "Avoid ...", "For {query_type}, ensure ...").
6. **Only guidance about identifiers and attributes generation**: No meta-commentary, no JSON, no Markdown fences.

## Output Format
Output ONLY the refined guidance text (plain text, no JSON wrapping, no Markdown fences). This text will be inserted verbatim into the generation prompt."""


def refine_idattr_guidance(
    current_guidance: str,
    results: List[Dict[str, Any]],
    feedback: str,
    task_name: str,
    llm_cfg: dict,
    logger: Optional[logging.Logger] = None,
    prompt_hook: Optional[Callable[[str], str]] = None,
) -> str:
    """Use the LLM to produce a refined guidance addendum.

    Parameters
    ----------
    prompt_hook : callable, optional
        If provided, called with the fully-built refine prompt string and
        expected to return the (possibly modified) prompt.  Used by
        ``HumanReviewer.review_refine_prompt`` to let a human edit the
        prompt before it is sent to the LLM.

    Returns the new guidance string.
    """
    log = logger or logging.getLogger(__name__)
    prompt = build_idattr_refine_prompt(current_guidance, results, feedback, task_name)
    if prompt_hook is not None:
        prompt = prompt_hook(prompt)

    refiner = Assistant(llm=llm_cfg)
    raw = ""
    for response in refiner.run([{"role": "user", "content": prompt}]):
        raw = response[-1]["content"]

    guidance = raw.strip()
    log.info("Refined guidance generated (length=%d chars)", len(guidance))
    return guidance


